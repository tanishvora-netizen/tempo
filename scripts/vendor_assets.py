"""Copy the frontend's third-party assets from node_modules into app/static/vendor/.

The running app makes zero external network calls, so Chart.js, the IBM Plex Sans
font files, and the Lucide icons the UI uses are vendored as static files.
Run with `make vendor` after `npm install`. Output is committed.
"""

from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NODE = ROOT / "node_modules"
VENDOR = ROOT / "app" / "static" / "vendor"

CHART_CANDIDATES = ("chart.umd.min.js", "chart.umd.js")
FONT_WEIGHTS = (400, 500, 600)
FONT_PATTERN = "ibm-plex-sans-latin-{weight}-normal.woff2"

# Every Lucide icon referenced by app/static/js (icon("name")). Keep this list in sync.
ICONS = (
    "layout-dashboard",
    "list-checks",
    "inbox",
    "sliders-horizontal",
    "shield-check",
    "handshake",
    "scroll-text",
    "x",
    "chevron-up",
    "chevron-down",
    "chevrons-up-down",
    "check",
    "circle-check",
    "info",
    "loader-circle",
    "refresh-cw",
    "triangle-alert",
    "download",
    "user-check",
    "file-text",
    "mail",
    "play",
    "credit-card",
    "landmark",
    "zap",
    "banknote",
    "circle-alert",
    "badge-check",
    "scan-text",
    "rotate-ccw",
    "lock",
    "square-pen",
    "circle-x",
    "history",
)

SVG_INNER = re.compile(r"<svg[^>]*>(.*)</svg>", re.DOTALL)


def copy_chart() -> Path:
    """Copy the Chart.js UMD build (minified if present) to vendor/chart.umd.min.js."""
    dist = NODE / "chart.js" / "dist"
    for name in CHART_CANDIDATES:
        source = dist / name
        if source.exists():
            target = VENDOR / "chart.umd.min.js"
            shutil.copyfile(source, target)
            shutil.copyfile(NODE / "chart.js" / "LICENSE.md", VENDOR / "chart.js.LICENSE.md")
            return target
    raise FileNotFoundError(f"no Chart.js UMD build in {dist}")


def copy_fonts() -> list[Path]:
    """Copy IBM Plex Sans latin woff2 files for the weights the UI uses."""
    files = NODE / "@fontsource" / "ibm-plex-sans" / "files"
    out_dir = VENDOR / "fonts"
    out_dir.mkdir(parents=True, exist_ok=True)
    copied = []
    for weight in FONT_WEIGHTS:
        name = FONT_PATTERN.format(weight=weight)
        source = files / name
        if not source.exists():
            raise FileNotFoundError(f"missing font file {source}")
        shutil.copyfile(source, out_dir / name)
        copied.append(out_dir / name)
    licence = NODE / "@fontsource" / "ibm-plex-sans" / "LICENSE"
    if licence.exists():
        shutil.copyfile(licence, out_dir / "OFL-LICENSE.txt")
    return copied


def icon_inner(name: str) -> str:
    """Return the child elements of one Lucide SVG, whitespace-collapsed."""
    source = NODE / "lucide-static" / "icons" / f"{name}.svg"
    if not source.exists():
        raise FileNotFoundError(f"missing Lucide icon {name}")
    match = SVG_INNER.search(source.read_text())
    if match is None:
        raise ValueError(f"cannot parse {source}")
    return " ".join(match.group(1).split())


def write_icons() -> Path:
    """Write the used icons as an ES module: export const ICONS = {name: '<path .../>'}."""
    out_dir = VENDOR / "icons"
    out_dir.mkdir(parents=True, exist_ok=True)
    icons = {name: icon_inner(name) for name in ICONS}
    body = json.dumps(icons, indent=2, sort_keys=True)
    target = out_dir / "icons.js"
    target.write_text(
        "// Generated by scripts/vendor_assets.py from lucide-static (ISC license). Do not edit.\n"
        f"export const ICONS = {body};\n"
    )
    shutil.copyfile(NODE / "lucide-static" / "LICENSE", out_dir / "LICENSE")
    return target


def main() -> int:
    if not NODE.exists():
        print("node_modules not found; run npm install first", file=sys.stderr)
        return 1
    VENDOR.mkdir(parents=True, exist_ok=True)
    written = [copy_chart(), *copy_fonts(), write_icons()]
    for path in written:
        print(f"wrote {path.relative_to(ROOT)} ({path.stat().st_size:,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
