"""Regenerate docs/RESULTS.md from data/precomputed/ (run `make precompute` first). README numbers are copied
only from that file."""

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

PRE = REPO / "data" / "precomputed"
OUT = REPO / "docs" / "RESULTS.md"
CALIBRATION = REPO / "data" / "demo" / "calibration.json"


def usd(cents: int) -> str:
    sign = "-" if cents < 0 else ""
    return f"{sign}${abs(cents) / 100:,.0f}"


def pct(x: float | None, digits: int = 2) -> str:
    return "n/a" if x is None else f"{x * 100:.{digits}f}%"


def policy_table(rows: list[dict], label: str) -> list[str]:
    out = [
        "| Policy | Value vs pay on due | Discounts taken | Card | Breach rate | 95% upper bound | Worst P10 balance | LATE | Credit drawn |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        out.append(
            f"| `{r['policy']}` | {usd(r['value_cents'])} | {r['discount_count']} | {r['card_count']} | "
            f"{pct(r['breach_rate'])} | {pct(r['breach_upper'])} | {usd(r['worst_p10_balance_cents'])} "
            f"({r['worst_p10_date']}) | {r['late_count']} | {usd(r['credit_drawn_cents'])} |"
        )
    return [f"**{label}**", "", *out, ""]


def extraction_table(ev: dict, split: str) -> list[str]:
    s = ev[split]
    out = [
        "| Reader | Answered | Accuracy (all invoices) | Precision (answered) | Discount precision | Discount recall |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for name, label in (
        ("regex", "Regex only"),
        ("model", "Model only (unverified)"),
        ("reconciled", "Reconciled (Tempo)"),
    ):
        m = s[name]
        out.append(
            f"| {label} | {m['answered']}/{m['n']} | {pct(m['accuracy'], 1)} | {pct(m['precision'], 1)} | "
            f"{pct(m['discount_precision'], 1)} | {pct(m['discount_recall'], 1)} |"
        )
    return out


def main() -> None:
    bundle = json.loads((PRE / "bundle.json").read_text())
    proof = json.loads((PRE / "proof.json").read_text())
    whatifs = json.loads((PRE / "whatifs.json").read_text())
    calib = json.loads(CALIBRATION.read_text())
    k, cert, solver, cv = bundle["kpis"], bundle["certification"], bundle["solver"], bundle["cash_value"]
    pol = {r["policy"]: r for r in proof["policies"]}
    true_pol = {r["policy"]: r for r in proof["policies_true_model"]}
    tempo, greedy, weekly = pol["tempo"], pol["greedy_discount"], pol["weekly_run"]
    ev = proof["extraction"]
    lines = [
        "# Results",
        "",
        f"Generated by `scripts/make_results.py` from `data/precomputed/` (input hash `{bundle['input_hash']}`, "
        f"built {bundle['built_at']}). All data is synthetic. Do not edit by hand.",
        "",
        "## Headline",
        "",
        f"- Tempo captures **{usd(tempo['value_cents'])}** over 13 weeks versus paying every bill on its due date. "
        f"Under the fitted forecast model, its chance of any end-of-day balance below the buffer is "
        f"**{pct(tempo['breach_rate'])}** (one-sided 95% upper bound {pct(tempo['breach_upper'])}) against a "
        f"{pct(k['epsilon'], 0)} target, on {cert['reported']['n']:,} fresh scenarios (seed C) no decision saw. "
        f"Under the generator's true payment model it is {pct(true_pol['tempo']['breach_rate'])} "
        f"(bound {pct(true_pol['tempo']['breach_upper'])}).",
        f"- Today's weekly AP run captures {usd(weekly['value_cents'])} and breaches in "
        f"{pct(weekly['breach_rate'])} of scenarios. Greedy discount-taking on the median forecast captures "
        f"{usd(greedy['value_cents'])} but breaches in {pct(greedy['breach_rate'])}. Tempo keeps "
        f"{tempo['value_cents'] / greedy['value_cents'] * 100:.0f}% of greedy's value at "
        f"{tempo['breach_rate'] / greedy['breach_rate'] * 100:.0f}% of its risk.",
        "- Certification covers sampling error, not model error: seeds B and C are drawn from the same fitted "
        "forecast. The true-model column below is the check on the model itself.",
        "",
        "## Certification (seed B decides, seed C reports)",
        "",
        f"Target EPSILON = {pct(cert['epsilon'], 0)}. Optimizer scenarios N = {cert['n']}, unprotected K = {cert['k']} "
        f"(in-sample breach {pct(cert['in_sample_rate'])}). Certification test: one-sided Wilson bound on 10,000 "
        f"seed-B scenarios with Bonferroni z = {cert['z_certify']} (0.05 split over 6 ladder steps).",
        "",
        "| N | K | In-sample breaches | Seed-B breaches | Seed-B rate | Seed-B bound | Pass | Solve (s) |",
        "|---:|---:|---:|---:|---:|---:|:---:|---:|",
    ]
    for s in cert["steps"]:
        lines.append(
            f"| {s['n']} | {s['k']} | {s['in_sample_breaches']} | {s['cert_breaches']} | {pct(s['cert_rate'])} "
            f"| {pct(s['cert_upper'])} | {'yes' if s['passed'] else 'no'} | {s['solve_seconds']:.2f} |"
        )
    rep = cert["reported"]
    lines += [
        "",
        f"Reported (seed C): {rep['breaches']} breaches in {rep['n']:,} scenarios = {pct(rep['rate'])}, "
        f"one-sided 95% Wilson upper bound {pct(rep['upper'])} ({'passes' if rep['passes'] else 'FAILS'}).",
        "",
    ]
    lines += ["## Policies on fresh scenarios", ""]
    lines += policy_table(proof["policies"], "Seed C under the fitted forecast model (headline)")
    lines += policy_table(
        proof["policies_true_model"], "Seed C under the generator's true payment model (robustness)"
    )
    lines += [
        '`greedy_p05` is the "smart spreadsheet": it takes a discount only when its return beats the cost of cash '
        "and the pointwise P5 balance path stays above the buffer. Checking each day separately is not enough to "
        "bound the chance of a breach on any day.",
        "",
        "## Ablation: joint vs per-day chance constraints",
        "",
    ]
    lines += policy_table(proof["ablations"], "Seed C")
    lines += [
        "`per_day_5pct` keeps each day's balance above the buffer in 95% of scenarios separately; "
        "`per_day_worst_case` is Bonferroni at 0.05 / 91 per day, which at 1,000 planning scenarios reduces to "
        "the pointwise minimum. Both are planned on the same 1,000 seed-A scenarios.",
        "",
        "## Sensitivity: Flex-style financing on",
        "",
        "Off in the headline (council C2): the fee is an assumption and Flex has no public API.",
        "",
    ]
    lad = proof["ladder_sensitivity"]
    lines += [
        "## Sensitivity: certification ladder starting at K = EPSILON * N",
        "",
        "The pre-registered ladder starts at K = 4 of 200 (2%), so the headline plan certifies with a wide margin. "
        "Starting at K = 10 (5% of 200) and stepping down, with Bonferroni over all nine rungs "
        f"(z = {lad['z']:.3f}), seed B certifies K = {lad['k']} (bound {pct(lad['cert_upper'])}). This row was "
        "added after the headline results were seen and is reported beside them, never instead of them "
        f"(docs/DECISIONS.md). Under the generator's true model: {pct(lad['true_breach_rate'])} "
        f"(bound {pct(lad['true_breach_upper'])}).",
        "",
    ]
    lines += policy_table([lad], "Seed C")
    fin = proof["financing_sensitivity"]
    lines += policy_table(
        [fin],
        f"Seed C, financing on ({fin['financed_count']} bills financed, "
        f"{usd(fin['financed_cents'])} repaid; certified: {'yes' if fin['certified'] else 'no'})",
    )
    lines += [
        "## Solver",
        "",
        f"`scipy.optimize.milp` (HiGHS), status {solver['status']}, MIP gap {pct(solver['mip_gap'], 4)}, "
        f"{solver['solve_seconds']:.2f} s for the certified plan ({solver['case_seconds']:.1f} s for the whole case "
        f"including certification and the cash-value re-solve).",
        "",
        "| Formulation | Rows | Nonzeros |",
        "|---|---:|---:|",
        f"| Naive SAA (every scenario x every day) | {solver['rows_naive']:,} | (not built) |",
        f"| Tempo reduced (check days, quantile cut, tight big-M) | {solver['rows']:,} | {solver['nonzeros']:,} |",
        "",
        f"Check days: {solver['check_days']}; scenario rows kept: {solver['scenario_rows']}.",
        "",
        "## Marginal value of cash",
        "",
        f"Forward difference with +{usd(cv['step_cents'])}: lambda = {cv['lam'] * 100:.2f} cents per extra dollar over "
        f"the horizon, about {pct(cv['annual_rate'])}/yr; cost of cash c = yield + lambda = {pct(cv['cost_of_cash'])}/yr"
        f"{' (credit-bound)' if cv['credit_bound'] else ''}.",
        "",
        "## What-if presets",
        "",
        "| Scenario | Value | Decisions changed | Breach (seed C) | Bound | K |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for p in whatifs["presets"]:
        r = p["certification"]["reported"]
        lines.append(
            f"| {p['label']} | {usd(p['kpis']['value_vs_pay_on_due_cents'])} | {len(p['diff'])} | "
            f"{pct(r['rate'])} | {pct(r['upper'])} | {p['certification']['k']} |"
        )
    lines += [
        "",
        "## Extraction (synthetic labeled set)",
        "",
        f"Provider for cached outputs: {bundle['provider']['model']}. Core terms = discount, discount days, net "
        "days, anchor, prox day.",
        "",
        "**Held-out split (one invoice-id hash bucket in four)**",
        "",
    ]
    lines += extraction_table(ev, "holdout")
    lines += ["", "**All invoices**", ""]
    lines += extraction_table(ev, "all")
    a = ev["all"]
    hc = a["hallucination_catch"]
    lines += [
        "",
        f"- Invoices with every field right and auto-accepted: {pct(a['invoice_all_correct_rate'], 1)}.",
        f"- Auto-accept coverage {pct(a['reconciled']['coverage'], 1)} at precision {pct(a['reconciled']['precision'], 1)}; "
        f"the rest go to Needs review.",
        f"- Wrong model readings: {hc['wrong_model_readings']}; rejected by quote verification: "
        f"{hc['rejected_by_verification']}; kept out of the plan by reconciliation: {hc['kept_out_of_plan']}.",
        f"- Documents a careful clerk would escalate (footer conflicts, the injection, terms changed by email): "
        f"{a['expected_reviews_routed']['routed']} of {a['expected_reviews_routed']['n']} routed to review.",
        "",
        "| Bucket | n | Correct |",
        "|---|---:|---:|",
    ]
    for status, b in a["buckets"].items():
        lines.append(f"| `{status}` | {b['n']} | {b['correct']} |")
    lines += [
        "",
        "**By difficulty tag (reconciled)**",
        "",
        "| Tag | n | Auto-accepted | Correct when accepted |",
        "|---|---:|---:|---:|",
    ]
    for tag, t in ev["by_tag"].items():
        m = t["reconciled"]
        lines.append(f"| `{tag}` | {m['n']} | {m['answered']} | {m['correct']} |")
    rows = calib["rows"]
    lines += [
        "",
        "## Starting-cash calibration (disclosed)",
        "",
        f"The only tuned generator parameter. Six pre-registered values swept on seed D (never seed C); rule used: "
        f"**{calib['rule']}** (see docs/DECISIONS.md).",
        "",
        "| Starting cash | pay_on_due breach | greedy breach | Tempo certified | Tempo value / greedy |",
        "|---:|---:|---:|:---:|---:|",
    ]
    for r in rows:
        lines.append(
            f"| {usd(r['starting_cash_cents'])} | {pct(r['pay_on_due_breach'])} | {pct(r['greedy_breach'])} | "
            f"{'yes' if r['tempo_certified'] else 'no'} | {r['tempo_value_share_of_greedy'] * 100:.0f}% |"
        )
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")
    update_readme(bundle, proof)
    tokens = demo_tokens(bundle, proof, whatifs)
    render_demo_script(tokens)
    update_submission(tokens)


README = REPO / "README.md"
START, END = "<!-- results:start -->", "<!-- results:end -->"
LABELS = {
    "pay_on_due": "Pay every bill on its due date",
    "weekly_run": "Weekly AP run, take discounts in the window (today's workflow)",
    "greedy_discount": "Greedy: take every discount the median forecast allows",
    "greedy_p05": "Smart spreadsheet: greedy on the P5 path, return beats cost of cash",
    "deterministic_p50": "Same optimizer on the median forecast only",
    "tempo": "**Tempo** (chance-constrained, certified)",
}


def update_readme(bundle: dict, proof: dict) -> None:
    """Replace the README's results block with numbers from the same precomputed files as RESULTS.md."""
    fitted = {r["policy"]: r for r in proof["policies"]}
    true = {r["policy"]: r for r in proof["policies_true_model"]}
    cert, solver, ev = bundle["certification"], bundle["solver"], proof["extraction"]["holdout"]
    rows = [
        "| Policy (13 weeks, 212 bills) | Value vs paying on due date | Breach probability (95% bound) | Under the true model |",
        "|---|---:|---:|---:|",
    ]
    for key, label in LABELS.items():
        f, t = fitted[key], true[key]
        rows.append(
            f"| {label} | {usd(f['value_cents'])} | {pct(f['breach_rate'])} ({pct(f['breach_upper'])}) | "
            f"{pct(t['breach_rate'])} |"
        )
    rec = ev["reconciled"]
    block = "\n".join(
        [
            START,
            f"Breach = any end-of-day balance below the {usd(bundle['company']['buffer_cents'])} buffer in 13 weeks, "
            f"measured on {cert['reported']['n']:,} fresh scenarios that no decision saw (target {pct(cert['epsilon'], 0)}).",
            "",
            *rows,
            "",
            f"- Certified with N = {cert['n']}, K = {cert['k']} on a separate 10,000-scenario set "
            f"(Bonferroni-corrected Wilson bound).",
            f"- Solver: {solver['rows']:,} rows instead of {solver['rows_naive']:,}, {solver['solve_seconds']:.2f} s, "
            f"gap {pct(solver['mip_gap'], 3)}.",
            f"- Extraction (synthetic, held-out split): Tempo auto-accepts {pct(rec['coverage'], 0)} of invoices' terms "
            f"at {pct(rec['precision'], 1)} precision and routes the rest to Needs review.",
            "",
            "Full tables, certification steps, ablations, what-ifs, and the extraction eval: [docs/RESULTS.md](docs/RESULTS.md).",
            END,
        ]
    )
    text = README.read_text()
    start, end = text.index(START), text.index(END) + len(END)
    README.write_text(text[:start] + block + text[end:])
    print(f"updated {README}")


if __name__ == "__main__":
    main()


TEMPLATE = REPO / "docs" / "demo_script.template.md"
DEMO_SCRIPT = REPO / "docs" / "DEMO_SCRIPT.md"
SUBMISSION = REPO / "SUBMISSION.md"


def demo_tokens(bundle: dict, proof: dict, whatifs: dict) -> dict[str, str]:
    """Every number the demo script and submission quote, from the precomputed files."""
    fitted = {r["policy"]: r for r in proof["policies"]}
    true = {r["policy"]: r for r in proof["policies_true_model"]}
    biggest = whatifs["customers"][0][0]
    preset = next(
        p
        for p in whatifs["presets"]
        if p["what_if"]["customer_id"] == biggest and p["what_if"]["delay_days"] == 14
    )
    rec = proof["extraction"]["holdout"]["reconciled"]
    return {
        "TEMPO_VALUE": usd(fitted["tempo"]["value_cents"]),
        "TEMPO_BREACH": pct(fitted["tempo"]["breach_rate"]),
        "TEMPO_BOUND": pct(fitted["tempo"]["breach_upper"]),
        "TEMPO_TRUE_BREACH": pct(true["tempo"]["breach_rate"]),
        "WEEKLY_VALUE": usd(fitted["weekly_run"]["value_cents"]),
        "WEEKLY_BREACH": pct(fitted["weekly_run"]["breach_rate"]),
        "GREEDY_VALUE": usd(fitted["greedy_discount"]["value_cents"]),
        "GREEDY_BREACH": pct(fitted["greedy_discount"]["breach_rate"]),
        "P05_BREACH": pct(fitted["greedy_p05"]["breach_rate"]),
        "P05_BOUND": pct(fitted["greedy_p05"]["breach_upper"]),
        "P05_TRUE": pct(true["greedy_p05"]["breach_rate"]),
        "LADDER_VALUE": usd(proof["ladder_sensitivity"]["value_cents"]),
        "LADDER_BREACH": pct(proof["ladder_sensitivity"]["breach_rate"]),
        "COST_OF_CASH": pct(bundle["cash_value"]["cost_of_cash"], 1) + "/yr",
        "ROWS_NAIVE": f"{bundle['solver']['rows_naive']:,}",
        "ROWS": f"{bundle['solver']['rows']:,}",
        "SOLVE_S": f"{bundle['solver']['solve_seconds']:.2f}",
        "PRESET_LABEL": preset["label"],
        "FLIPS": str(len(preset["diff"])),
        "REVIEW_COUNT": str(sum(r["needs_review"] for r in bundle["bills"])),
        "COVERAGE": pct(rec["coverage"], 0),
        "PRECISION": pct(rec["precision"], 1),
    }


def render(text: str, tokens: dict[str, str]) -> str:
    for key, value in tokens.items():
        text = text.replace(f"⟨{key}⟩", value)
    if "⟨" in text:
        raise ValueError("unfilled token in template: " + text[text.index("⟨") : text.index("⟨") + 30])
    return text


def render_demo_script(tokens: dict[str, str]) -> None:
    DEMO_SCRIPT.write_text(render(TEMPLATE.read_text(), tokens))
    print(f"wrote {DEMO_SCRIPT}")


def update_submission(tokens: dict[str, str]) -> None:
    start, end = "<!-- description:start -->", "<!-- description:end -->"
    description = render(
        "Tempo decides the best day and rail to pay every bill. It captures early-payment discounts and card "
        "rewards while keeping the chance that cash dips below the company's buffer under 5%, certified on fresh "
        "scenarios. AP teams still time payments by spreadsheet. Tempo reads terms from invoices and email threads "
        "with a local model that only quotes; code verifies every quote and cross-checks a deterministic parser. "
        "Uncertain bills go to a review queue, including a prompt-injection invoice. It forecasts 13 weeks of cash "
        "from customer payment behavior and solves one chance-constrained MILP for all 212 bills. On 10,000 unseen "
        "scenarios it earns ⟨TEMPO_VALUE⟩ over paying on due dates at a ⟨TEMPO_BREACH⟩ breach rate, while today's "
        "weekly run breaches ⟨WEEKLY_BREACH⟩. Explanations, live what-ifs, a negotiation agent, a hash-chained "
        "audit log, and Ramp API payload previews complete it. All data is synthetic; nothing is sent.",
        tokens,
    )
    text = SUBMISSION.read_text()
    i, j = text.index(start), text.index(end) + len(end)
    SUBMISSION.write_text(text[:i] + start + "\n" + description + "\n" + end + text[j:])
    print(f"updated {SUBMISSION} ({len(description.split())} words)")
